    def _on_name_editing_finished(self):
        """Check for duplicate assessment name as soon as the user leaves the name field.

        If the name already exists, immediately ask whether to create a new version.
        On confirmation, repopulate the layer table to include Output Layers (blue)
        so the user can configure everything with full context before clicking Next.
        """
        if self._creating_new_version or not self.admin_manager:
            return

        assessment_name = self.lineEdit_name.text().strip().replace(' ', '_')
        if not assessment_name:
            return

        executor = AssessmentExecutor(
            self.project_id, self.admin_manager, self.project_db_id
        )
        if executor.validate_assessment_name(assessment_name):
            return  # Name is available — nothing to do

        reply = QtWidgets.QMessageBox.question(
            self,
            tr('dialog.exists_title'),
            tr('dialog.exists_body', name=assessment_name),
            QtWidgets.QMessageBox.StandardButton.Yes | QtWidgets.QMessageBox.StandardButton.No,
            QtWidgets.QMessageBox.StandardButton.No
        )
        if reply == QtWidgets.QMessageBox.StandardButton.Yes:
            self._creating_new_version = True
            assessments = self.admin_manager.get_assessments_for_project(
                self.project_db_id
            )
            for a in assessments:
                if a['name'] == assessment_name:
                    self._existing_assessment_id = a['id']
                    break
            # Repopulate table from scratch so Output Layers appear immediately
            self.populate_layers()
            self._add_output_layers_to_table()
        else:
            # Clear the name field so the user picks a different one
            self.lineEdit_name.clear()
            self.lineEdit_name.setFocus()

    def populate_layers(self):
        """Populate the table widget with vector layers from the 'Base Layers' group folder."""
        self.tableWidget_layers.setRowCount(0)

        root = QgsProject.instance().layerTreeRoot()

        # Look for a group called "Base Layers" to find input layers
        base_layers_group = root.findGroup("Base Layers")

        if not base_layers_group:
            QMessageBox.warning(
                self,
                tr('dialog.no_base_group_title'),
                tr('dialog.no_base_group_body')
            )
            return

        tree_layers = base_layers_group.findLayers()

        for tree_layer in tree_layers:
            layer = tree_layer.layer()

            if not layer or not isinstance(layer, QgsVectorLayer):
                continue

            row_position = self.tableWidget_layers.rowCount()
            self.tableWidget_layers.insertRow(row_position)

            # Column 0: Layer name
            layer_item = QTableWidgetItem(layer.name())
            self.tableWidget_layers.setItem(row_position, 0, layer_item)

            # Column 1: Geometry type
            geometry_type = QgsWkbTypes.displayString(layer.wkbType())
            geometry_item = QTableWidgetItem(geometry_type)
            self.tableWidget_layers.setItem(row_position, 1, geometry_item)

            # Column 2: Status dropdown
            status_combo = self._make_status_combo()
            self.tableWidget_layers.setCellWidget(row_position, 2, status_combo)

        self.tableWidget_layers.resizeColumnsToContents()

    def _add_output_layers_to_table(self):
        """Add Output Layers to the table widget with a blue background (v2+ mode only)."""
        from qgis.core import QgsProject, QgsVectorLayer, QgsWkbTypes
        from qgis.PyQt.QtGui import QColor

        root = QgsProject.instance().layerTreeRoot()
        output_group = root.findGroup("Output Layers")
        if not output_group:
            return

        light_blue = QColor(173, 216, 230)

        for tree_layer in output_group.findLayers():
            layer = tree_layer.layer()
            if not layer or not isinstance(layer, QgsVectorLayer):
                continue

            row = self.tableWidget_layers.rowCount()
            self.tableWidget_layers.insertRow(row)

            layer_item = QTableWidgetItem(layer.name())
            layer_item.setBackground(light_blue)
            self.tableWidget_layers.setItem(row, 0, layer_item)

            geom_item = QTableWidgetItem(
                QgsWkbTypes.displayString(layer.wkbType())
            )
            geom_item.setBackground(light_blue)
            self.tableWidget_layers.setItem(row, 1, geom_item)

            status_combo = self._make_status_combo()
            self.tableWidget_layers.setCellWidget(row, 2, status_combo)

        self.tableWidget_layers.resizeColumnsToContents()

    def on_status_changed(self, _index=None):
        """Handle status change to ensure only one layer is set as Target."""
        sender = self.sender()
        if isinstance(sender, QComboBox) and self._status_of(sender) == self.STATUS_TARGET:
            for row in range(self.tableWidget_layers.rowCount()):
                combo = self.tableWidget_layers.cellWidget(row, 2)
                if combo and combo is not sender and self._status_of(combo) == self.STATUS_TARGET:
                    self._set_status(combo, self.STATUS_DO_NOT_INCLUDE)

    def validate_page_1(self):
        """Validate page 1 before allowing user to proceed."""
        if not self.lineEdit_name.text().strip():
            QtWidgets.QMessageBox.warning(
                self,
                tr('dialog.val_title'),
                tr('dialog.val_name_required')
            )
            return False

        # Check if exactly one layer is set as Target
        target_count = 0
        for row in range(self.tableWidget_layers.rowCount()):
            combo = self.tableWidget_layers.cellWidget(row, 2)
            if combo and self._status_of(combo) == self.STATUS_TARGET:
                target_count += 1

        if target_count == 0:
            QtWidgets.QMessageBox.warning(
                self,
                tr('dialog.val_title'),
                tr('dialog.val_no_target')
            )
            return False
        elif target_count > 1:
            QtWidgets.QMessageBox.warning(
                self,
                tr('dialog.val_title'),
                tr('dialog.val_multi_target')
            )
            return False

        # Validate geometry types match
        target_layer = None
        target_layer_name = None
        assessment_layers = []

        for row in range(self.tableWidget_layers.rowCount()):
            layer_name_item = self.tableWidget_layers.item(row, 0)
            combo = self.tableWidget_layers.cellWidget(row, 2)

            if layer_name_item and combo:
                layer_name = layer_name_item.text()
                status = self._status_of(combo)

                layers = QgsProject.instance().mapLayersByName(layer_name)
                if layers:
                    layer = layers[0]
                    if status == self.STATUS_TARGET:
                        target_layer = layer
                        target_layer_name = layer_name
                    elif status == self.STATUS_INCLUDE:
                        assessment_layers.append((layer_name, layer))

        if target_layer and assessment_layers:
            if isinstance(target_layer, QgsVectorLayer):
                target_geom_type = target_layer.geometryType()

                for assessment_name, assessment_layer in assessment_layers:
                    if isinstance(assessment_layer, QgsVectorLayer):
                        if assessment_layer.geometryType() != target_geom_type:
                            target_type_name = QgsWkbTypes.displayString(target_layer.wkbType())
                            assessment_type_name = QgsWkbTypes.displayString(assessment_layer.wkbType())

                            QtWidgets.QMessageBox.warning(
                                self,
                                tr('dialog.val_title'),
                                tr('dialog.val_geom_mismatch',
                                   assess=assessment_name, assess_type=assessment_type_name,
                                   target=target_layer_name, target_type=target_type_name)
                            )
                            return False
                    else:
                        QtWidgets.QMessageBox.warning(
                            self,
                            tr('dialog.val_title'),
                            tr('dialog.val_not_vector', assess=assessment_name)
                        )
                        return False

        # Migrate selected layers to SpatiaLite
        migration_service = LayerMigrationService(self.admin_manager, self.project_db_id)
        layers_dict = self._collect_selected_layers()
        if not migration_service.migrate_selected_layers(layers_dict, parent_widget=self):
            pass  # Migration failed, but allow user to continue

        return True

